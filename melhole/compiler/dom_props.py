"""Writes melhole/compiler/dom_props.ml from reason-react's ReactDOM.domProps.

python3 melhole/compiler/dom_props.py path/to/reason-react/melange/ReactDOM.rei > melhole/compiler/dom_props.ml
"""

import re
import sys

source = open(sys.argv[1]).read()
record = source[source.index("type domProps = {"):source.index("external stringToComponent")]
fields = re.findall(r"((?:\[@[^\]]*\]\s*)*)\s*(\w+)\s*:\s*option\(([^,]*?)\),", record)

booleanish = {"draggable", "spellCheck", "contentEditable"}
properties = {"value": "Text", "checked": "Flag", "selected": "Flag", "muted": "Flag"}
renamed = {"className": "class", "htmlFor": "for", "defaultValue": "value", "defaultChecked": "checked"}
events = {
    "onDoubleClick": "dblclick", "onChange": "input", "onFocus": "focusin", "onBlur": "focusout",
}
skipped = {"key", "children"}
hyphenated = set("""accentHeight alignmentBaseline arabicForm baselineShift capHeight clipPath clipRule
colorInterpolation colorInterpolationFilters colorProfile colorRendering dominantBaseline enableBackground
fillOpacity fillRule floodColor floodOpacity fontFamily fontSize fontSizeAdjust fontStretch fontStyle
fontVariant fontWeight glyphName glyphOrientationHorizontal glyphOrientationVertical horizAdvX horizOriginX
imageRendering letterSpacing lightingColor markerEnd markerMid markerStart overlinePosition overlineThickness
paintOrder panose1 pointerEvents renderingIntent shapeRendering stopColor stopOpacity strikethroughPosition
strikethroughThickness strokeDasharray strokeDashoffset strokeLinecap strokeLinejoin strokeMiterlimit
strokeOpacity strokeWidth textAnchor textDecoration textRendering underlinePosition underlineThickness
unicodeBidi unicodeRange unitsPerEm vAlphabetic vHanging vIdeographic vMathematical vectorEffect vertAdvY
vertOriginX vertOriginY wordSpacing writingMode xHeight acceptCharset httpEquiv""".split())
namespaced = {"xlinkActuate": "xlink:actuate", "xlinkArcrole": "xlink:arcrole", "xlinkHref": "xlink:href",
              "xlinkRole": "xlink:role", "xlinkShow": "xlink:show", "xlinkTitle": "xlink:title",
              "xlinkType": "xlink:type", "xmlBase": "xml:base", "xmlLang": "xml:lang", "xmlSpace": "xml:space"}

cases = {}
for attributes, name, kind in fields:
    if name in skipped or name in cases:
        continue
    alias = re.search(r'@mel\.as "([^"]+)"', attributes)
    html = renamed.get(name, alias.group(1) if alias else name)
    if name in hyphenated:
        html = re.sub(r"([A-Z0-9])", lambda m: "-" + m.group(1).lower(), name)
    html = namespaced.get(name, html)
    if re.match(r"aria[A-Z]", html):
        html = "aria-" + html[4:].lower()
    family = re.match(r"React\.Event\.(\w+)\.t => unit", kind.strip())
    if family:
        event = events.get(name, name[2:].lower())
        cases[name] = f'Handler ("{event}", "{family.group(1)}")'
    elif kind == "style":
        cases[name] = "Style"
    elif kind == "domRef":
        cases[name] = "Ref"
    elif name == "dangerouslySetInnerHTML":
        cases[name] = "Inner_html"
    elif name.startswith("suppress"):
        cases[name] = "Ignored"
    elif name in properties:
        cases[name] = f'Property ("{name}", {properties[name]})'
    else:
        value = {
            "string": "Text", "int": "Integer", "float": "Decimal",
            "bool": "Booleanish" if html.startswith("aria-") or name in booleanish else "Flag",
        }.get(kind)
        if value is None:
            sys.exit(f"unknown type {kind} for {name}")
        cases[name] = f'Attribute ("{html}", {value})'

def constructor(name):
    return name[0].upper() + name[1:]


print("(* Generated by melhole/compiler/dom_props.py from reason-react's ReactDOM.domProps. *)")
print()
print("module Prop = struct")
print("  type t =")
for name in cases:
    print(f'    | {constructor(name)} [@as "{name}"]')
print("  [@@deriving of_string, to_string, enumerate]")
print("end")
print()
print("type value = Text | Flag | Booleanish | Integer | Decimal")
print()
print("type kind =")
print("  | Attribute of string * value")
print("  | Property of string * value")
print("  | Handler of string * string")
print("  | Style")
print("  | Ref")
print("  | Inner_html")
print("  | Ignored")
print()
print("let kind (prop : Prop.t) =")
print("  match prop with")
for name, case in cases.items():
    print(f"  | {constructor(name)} -> {case}")
